pub fn matches(pattern: &str, path: &str) -> bool {
    let left: Vec<_> = pattern.split('/').collect();
    let right: Vec<_> = path.split('/').collect();
    left.len() == right.len()
        && left.iter().zip(right).all(|(expected, actual)| {
            *expected == actual
                || expected.starts_with('{') && expected.ends_with('}') && !actual.is_empty()
        })
}
fn specificity(pattern: &str) -> usize {
    pattern.split('/').filter(|p| !p.starts_with('{')).count()
}
pub fn route(method: &str, path: &str) -> Option<&'static Route> {
    let method = if method == "HEAD" { "GET" } else { method };
    ROUTES
        .iter()
        .filter(|r| r.method == method && matches(r.path, path))
        .max_by_key(|r| specificity(r.path))
}
pub fn view_actions(query: Option<&str>) -> Result<&'static [Action], ApiError> {
    let paths: Vec<_> = url::form_urlencoded::parse(query.unwrap_or("").as_bytes())
        .filter(|(k, _)| k == "path")
        .map(|(_, v)| v.into_owned())
        .collect();
    let [path] = paths.as_slice() else {
        return Err(invalid_view());
    };
    validate_view_path(path)?;
    VIEWS
        .iter()
        .filter(|(p, _)| matches(p, path))
        .max_by_key(|(p, _)| specificity(p))
        .map(|(_, a)| *a)
        .ok_or_else(session_only)
}
pub fn validate_view_path(path: &str) -> Result<(), ApiError> {
    if !path.starts_with('/')
        || path.starts_with("//")
        || path.contains(['\\', '?', '#'])
        || path.chars().any(char::is_control)
    {
        return Err(invalid_view());
    }
    Ok(())
}
fn invalid_view() -> ApiError {
    ApiError::new(
        axum::http::StatusCode::BAD_REQUEST,
        "invalid_view",
        "올바른 화면 경로가 필요합니다.",
    )
}
